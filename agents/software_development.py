    def _execute_sandboxed_test(self, code: str) -> Tuple[bool, str, Any]:
        """
        Executes generated script in a restricted namespace without filesystem/network access.
        """
        # Restrict builtins to safe execution
        safe_builtins = {
            "__build_class__": __build_class__,
            "isinstance": isinstance,
            "int": int,
            "float": float,
            "str": str,
            "bool": bool,
            "list": list,
            "dict": dict,
            "len": len,
            "any": any,
            "all": all,
            "print": print,
            "AssertionError": AssertionError,
            "Exception": Exception,
            "ValueError": ValueError,
            "TypeError": TypeError
        }
        exec_env = {
            "__builtins__": safe_builtins,
            "__name__": "__main__"
        }

        try:
            compiled = compile(code, "<vendor_monitor_script>", "exec")
            exec(compiled, exec_env)
            
            test_fn = exec_env.get("run_self_test")
            if not callable(test_fn):
                return False, "", "run_self_test function was not defined in generated script."
            
            output = test_fn()
            return True, str(output), None
        except AssertionError as ae:
            return False, "", f"Assertion failed during self-test: {str(ae)}"
        except Exception as e:
            return False, "", f"Runtime error in self-test execution: {str(e)}"
